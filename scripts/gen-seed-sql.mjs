// Regenerates the seed-pin migration from src/lib/map/seed-pins.json.
// Usage: node scripts/gen-seed-sql.mjs  (paste the output between the BEGIN/END GENERATED SEED
// markers in supabase/migrations/20261118000000_community_map.sql)
import { readFileSync } from "node:fs";

const pins = JSON.parse(readFileSync(new URL("../src/lib/map/seed-pins.json", import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const rows = pins.map(
  (p) =>
    `  (${q(p.id)}, 'approved', ${q(p.type)}, ${q(p.name)}, ${q(p.description)}, ${q(p.region)}, ${p.x}, ${p.y}, 'Leonida Vice Guide', true, ${p.approximate}, '2026-11-18T00:00:00Z', '2026-11-18T00:00:00Z')`,
);
console.log(`-- Seed pins (official region and landmark names). Generated by scripts/gen-seed-sql.mjs.
-- Safe to re-run: existing rows (including moderator edits) are left alone.
insert into public.pins (id, status, type, name, description, region, x, y, gamer_tag, is_seed, approximate, created_at, reviewed_at)
values
${rows.join(",\n")}
on conflict (id) do nothing;`);
