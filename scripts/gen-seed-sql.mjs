// Regenerates the seed-pin SQL from src/lib/map/seed-pins.json.
// Usage: node scripts/gen-seed-sql.mjs > /tmp/seed.sql
// The output is idempotent: new rows are inserted, existing rows (including moderator edits) are left
// alone except that `source` is set. It is pasted between the BEGIN/END GENERATED SEED markers in
// supabase/migrations/20261118000400_pin_types_and_source.sql. The seed list in
// supabase/migrations/20261118000000_community_map.sql is the original 14 pins and stays as is.
import { readFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../src/lib/map/${f}`, import.meta.url), "utf8"));
const pins = [...read("seed-pins.json"), ...read("gtadb-pins.json")];
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const rows = pins.map(
  (p) =>
    `  (${q(p.id)}, 'approved', ${q(p.type)}, ${q(p.name)}, ${q(p.description)}, ${q(p.region)}, ${p.x}, ${p.y}, 'Leonida Vice Guide', true, ${p.approximate}, ${q(p.source ?? "official")}, '2026-11-18T00:00:00Z', '2026-11-18T00:00:00Z')`,
);
console.log(`-- Seed pins: places Rockstar has officially named (source 'official') plus GTADB.org landmark data (source 'gtadb', CC BY 4.0, see docs/DATA_CREDITS.md).\n-- Generated by scripts/gen-seed-sql.mjs.
insert into public.pins (id, status, type, name, description, region, x, y, gamer_tag, is_seed, approximate, source, created_at, reviewed_at)
values
${rows.join(",\n")}
on conflict (id) do update set source = excluded.source;`);
