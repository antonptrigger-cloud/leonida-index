#!/usr/bin/env python3
"""Builds src/lib/map/official-labels.json: the names printed on the official poster, as a label layer for the official base.

Every name and position comes from official-places.json (read off Rockstar's Leonida Map & Cover Art Poster). The poster has its
own print, so the app draws one of these labels only while the printed text is too small to read (`printedPx` = height of the
printed letters in source pixels; see LeafletMap.tsx). x/y are pin-space coordinates (inverse of the official transform), so a
label follows the same transform as every pin.

Run:  python3 scripts/official/build_labels.py   (after build_official_transform.py)
"""
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
places = json.loads((ROOT / "scripts/official/official-places.json").read_text())["places"]
art_t = json.loads((ROOT / "src/lib/map/pin-transform-art.json").read_text())
off = json.loads((ROOT / "src/lib/map/art-to-official.json").read_text())
(a, b), (c, d), (e, f) = off["matrix"]
AP = art_t["points"]

def art_to_pin(sx, sy):
    best = None
    for i, j, k in art_t["triangles"]:
        A, B, C = (np.array(AP[n]["art"]) for n in (i, j, k))
        T = np.array([[A[0]-C[0], B[0]-C[0]], [A[1]-C[1], B[1]-C[1]]])
        w12 = np.linalg.solve(T, np.array([sx, sy]) - C); w = np.append(w12, 1 - w12.sum())
        if best is None or w.min() > best[0]: best = (w.min(), w, (i, j, k))
        if w.min() >= 0: break
    _, w, t = best
    return [float(sum(wi * AP[n]["legacy"][dd] for wi, n in zip(w, t))) for dd in (0, 1)]

def official_to_pin(sx, sy):
    det = a * d - b * c
    px, py = sx - e, sy - f
    return art_to_pin((px * d - py * c) / det, (-px * b + py * a) / det)

MAIN_COUNTIES = {"Lummox County", "Leonard County", "Kelly County", "Vice-Dale County", "Mariana County"}
# height of the printed letters in official source px (from OCR boxes); defaults per kind
PRINTED = {"Vice City": 83, "Port Gellhorn": 90, "Hamlet": 77, "Vice Beach": 83, "Key Lento": 62, "Grassrivers": 52, "Ambrosia": 43,
           "Mount Kalaga National Park": 38, "Southwind": 98, "Capri": 68, "Grayson": 57, "Millport": 68, "Bonanza": 53, "Belville": 51}
DEFAULT_H = {"county": 40, "region": 60, "district": 40, "city": 55, "place": 32, "water": 40, "island": 42}
URL = "https://www.rockstargames.com/VI/downloads"
QUOTE = "Printed on the Leonida Map & Cover Art Poster"

out = []
for p in places:
    h = 300 if p["name"] in MAIN_COUNTIES else PRINTED.get(p["name"], DEFAULT_H[p["kind"]])
    x, y = official_to_pin(p["x"], p["y"])
    out.append(dict(id="olabel-" + "".join(ch.lower() if ch.isalnum() else "-" for ch in p["name"]).strip("-"), name=p["name"], kind=p["kind"],
                    x=round(x, 2), y=round(y, 2), minZoom=0, approximate=False, source="official", sourceUrl=URL, sourceQuote=QUOTE,
                    placement="Centre of the printed label on the official poster", printedPx=h, src=[p["x"], p["y"]]))
(ROOT / "src/lib/map/official-labels.json").write_text(json.dumps(dict(version=1, note="Generated by scripts/official/build_labels.py from scripts/official/official-places.json. Names and positions are read off Rockstar's official map poster.", labels=out), indent=1) + "\n")
print(len(out), "labels")
